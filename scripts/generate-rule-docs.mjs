#!/usr/bin/env node
/**
 * Generate `docs/rules.md` from the rule registry.
 *
 * Hand-written rule documentation rots: a severity changes, a rationale is
 * tightened, and the docs keep the old text. Generating it means the published
 * rule reference is always the code that runs. CI regenerates the file and
 * fails if the committed version differs (`npm run docs:check`).
 */

import { writeFileSync, readFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { listRules } from "../src/rules/index.js";
import { NAME, VERSION } from "../src/version.js";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const TARGET = join(ROOT, "docs", "rules.md");

const rules = listRules();
const categories = [...new Set(rules.map((rule) => rule.category))];

/** @param {string} text */
function anchor(text) {
  return text.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

const lines = [];

lines.push(`# Rule reference`);
lines.push("");
lines.push(
  `<!-- Generated by scripts/generate-rule-docs.mjs from src/rules/. Do not edit by hand. -->`,
);
lines.push("");
lines.push(
  `${NAME} ${VERSION} ships **${rules.length} rules** in ${categories.length} categories. Each rule has a stable id; ids are never reused, so a ` +
    `baseline or a \`--ignore\` entry keeps meaning the same thing across releases.`,
);
lines.push("");
lines.push(`Run \`${NAME} explain <id>\` to read a rule in the terminal, or \`${NAME} rules\` to list them.`);
lines.push("");

lines.push("## Severity levels");
lines.push("");
lines.push("| Level | Meaning | Typical consequence of ignoring it |");
lines.push("| --- | --- | --- |");
lines.push("| `critical` | Removes a control that stops a poisoned tool result from acting | Code execution or silent exfiltration |");
lines.push("| `high` | Grants access an agent does not need for the task | A mistake becomes a real change to real data |");
lines.push("| `medium` | Weakens defence in depth, or depends on a trusted network position | Exploitable when something else is off |");
lines.push("| `low` | Correctness or hygiene problem with a security flavour | Confusing failures, silent misconfiguration |");
lines.push("| `info` | Context only | Nothing |");
lines.push("");

lines.push("## Summary");
lines.push("");
lines.push("| Id | Severity | Category | Rule |");
lines.push("| --- | --- | --- | --- |");
for (const rule of rules) {
  lines.push(`| [\`${rule.id}\`](#${rule.id.toLowerCase()}) | ${rule.severity} | ${rule.category} | ${rule.title} |`);
}
lines.push("");

for (const category of categories) {
  lines.push(`## ${category}`);
  lines.push("");
  for (const rule of rules.filter((candidate) => candidate.category === category)) {
    lines.push(`<a id="${rule.id.toLowerCase()}"></a>`);
    lines.push("");
    lines.push(`### ${rule.id} · ${rule.title}`);
    lines.push("");
    lines.push(`**Severity** \`${rule.severity}\` · **Applies to** ${rule.target} · **Slug** \`${anchor(`${rule.id} ${rule.title}`)}\``);
    lines.push("");
    lines.push(rule.summary);
    lines.push("");
    lines.push("**Why it matters**");
    lines.push("");
    lines.push(rule.why);
    lines.push("");
    lines.push("**Fix**");
    lines.push("");
    lines.push(rule.remediation);
    if (rule.references && rule.references.length > 0) {
      lines.push("");
      lines.push("**References**");
      lines.push("");
      for (const reference of rule.references) lines.push(`- <${reference}>`);
    }
    lines.push("");
  }
}

lines.push("## Adding a rule");
lines.push("");
lines.push(
  "Rules live in `src/rules/<category>.js` and export a `Rule` object. `src/rules/index.js` validates the whole set at " +
    "import time: a duplicate id, an unknown severity, a missing rationale, or a `check` that is not a function is a hard " +
    "error, not a warning. `test/rules.test.js` requires a positive *and* a negative case per rule — a rule that only " +
    "ever fires is as much a bug as one that never fires.",
);
lines.push("");

const contents = lines.join("\n");
mkdirSync(dirname(TARGET), { recursive: true });

const check = process.argv.includes("--check");
if (check) {
  const existing = existsSync(TARGET) ? readFileSync(TARGET, "utf8") : "";
  if (existing !== contents) {
    process.stderr.write("docs/rules.md is out of date. Run `npm run docs` and commit the result.\n");
    process.exit(1);
  }
  process.stdout.write("docs/rules.md is up to date\n");
} else {
  writeFileSync(TARGET, contents, "utf8");
  process.stdout.write(`wrote docs/rules.md (${rules.length} rules)\n`);
}
